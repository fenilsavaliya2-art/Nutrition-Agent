def check_harmful_content(text: str) -> tuple[bool, str]:
    """
    Returns (is_safe, reason).
    is_safe=False means the query should be blocked.
    """
    text_lower = text.lower()
    for topic in BLOCKED_TOPICS:
        if topic in text_lower:
            return False, (
                f"I'm unable to provide advice related to '{topic}'. "
                "For safe and personalized guidance, please consult a qualified healthcare "
                "professional or registered dietitian."
            )
    return True, ""


def sanitize_user_input(text: str) -> str:
    """Basic sanitization — strip dangerous characters."""
    # Remove potential prompt-injection markers
    for marker in ["###", "SYSTEM:", "IGNORE PREVIOUS", "jailbreak", "<|"]:
        text = text.replace(marker, "")
    return text.strip()[:2000]  # cap length


def validate_age(age) -> tuple[bool, str]:
    try:
        age = int(age)
        if age < 1 or age > 120:
            return False, "Age must be between 1 and 120."
        return True, ""
    except (ValueError, TypeError):
        return False, "Age must be a valid number."


def validate_user_profile(profile: dict) -> tuple[bool, str]:
    """Validate all required user profile fields."""
    required = ["name", "age", "diet_preference", "city", "country"]
    for field in required:
        if not profile.get(field, "").strip():
            return False, f"Field '{field}' is required."

    age_valid, age_msg = validate_age(profile.get("age", ""))
    if not age_valid:
        return False, age_msg

    if profile.get("diet_preference", "").lower() not in ["vegetarian", "non-vegetarian", "vegan"]:
        return False, "Diet preference must be Vegetarian, Non-Vegetarian, or Vegan."

    return True, ""
